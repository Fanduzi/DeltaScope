//go:build postgresql

package audit

import (
	"context"
	"testing"

	"github.com/Fanduzi/DeltaScope/internal/domain/policy"
	"github.com/Fanduzi/DeltaScope/internal/domain/rule"
	"github.com/Fanduzi/DeltaScope/internal/domain/rule/ddl"
	"github.com/Fanduzi/DeltaScope/internal/domain/spec"
)

func TestPGGenerationPipeline(t *testing.T) {
	reg := rule.NewRegistry()
	if err := ddl.Register(reg, policy.Policy{Rules: map[string]policy.RulePolicy{
		"ddl.pg.column.generation.declaration.valid": {Enabled: true},
		"ddl.pg.column.identity.cycle.warn":          {Enabled: true},
	}}); err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		sql, verdict, reason     string
		blockers, warnings, gaps int
	}{
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY)", "pass", "", 0, 0, 0},
		{"ALTER TABLE app.t ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY(CYCLE)", "review", "identity_cycle", 0, 1, 0},
		{"ALTER TABLE t ADD COLUMN id bigint GENERATED ALWAYS AS IDENTITY(NO CYCLE)", "pass", "", 0, 0, 0},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(START 2147483648 MAXVALUE 9223372036854775807))", "pass", "", 0, 0, 0},
		{"CREATE TABLE t(id bigint[] GENERATED ALWAYS AS IDENTITY)", "reject", "identity_type_inapplicable", 1, 0, 0},
		{"CREATE TABLE t(id pg_catalog.text GENERATED ALWAYS AS IDENTITY)", "reject", "identity_type_inapplicable", 1, 0, 0},
		{"ALTER TABLE t ADD COLUMN id bigint NULL GENERATED ALWAYS AS IDENTITY", "reject", "identity_null_conflict", 1, 0, 0},
		{"CREATE TABLE t(id bigint DEFAULT 1 GENERATED ALWAYS AS IDENTITY)", "reject", "generation_default_conflict", 1, 0, 0},
		{"CREATE TABLE t(a int DEFAULT 0 GENERATED ALWAYS AS (1) STORED)", "reject", "generation_default_conflict", 1, 0, 0},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(INCREMENT 0 CYCLE))", "reject", "identity_increment_zero", 1, 0, 0},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(CACHE 0))", "reject", "identity_cache_invalid", 1, 0, 0},
		{"CREATE TABLE t(id smallint GENERATED ALWAYS AS IDENTITY(MAXVALUE 32768))", "reject", "identity_bounds_invalid", 1, 0, 0},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(START 0))", "reject", "identity_start_out_of_bounds", 1, 0, 0},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(CYCLE NO CYCLE))", "review", "", 0, 0, 2},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY)", "review", "", 0, 0, 2},
		{"CREATE TABLE t(id custom_type GENERATED ALWAYS AS IDENTITY)", "review", "", 0, 0, 2},
		{"CREATE TABLE t(id bigint GENERATED ALWAYS AS IDENTITY(START 9223372036854775808))", "review", "", 0, 0, 2},
		{"CREATE TABLE t(a int GENERATED ALWAYS AS (1) STORED)", "pass", "", 0, 0, 0},
		{"ALTER TABLE t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY(CYCLE)", "pass", "", 0, 0, 0},
	} {
		t.Run(tc.sql, func(t *testing.T) {
			r, err := EvaluateStatements(context.Background(), reg, t27Statements(t, spec.DialectPostgreSQL, tc.sql))
			if err != nil || string(r.Verdict) != tc.verdict || r.Summary.Blockers != tc.blockers || r.Summary.Warnings != tc.warnings {
				t.Fatalf("result=%+v err=%v", r, err)
			}
			if len(r.Statements[0].EvidenceGaps) != tc.gaps {
				t.Fatalf("gaps=%+v", r.Statements[0].EvidenceGaps)
			}
			for _, f := range r.Statements[0].Findings {
				if f.Metadata["reason_code"] != tc.reason || f.Location == nil {
					t.Fatalf("finding=%+v", f)
				}
			}
		})
	}
}
