func TestGenerationDeclarationSeam(t *testing.T) {
	for _, prefix := range []string{"CREATE TABLE t (id ", "ALTER TABLE t ADD COLUMN id "} {
		for _, tc := range []struct {
			decl                      string
			identities, stored, width int
			mode                      string
			null                      bool
		}{
			{"bigint GENERATED ALWAYS AS IDENTITY", 1, 0, 64, "a", false},
			{"integer GENERATED BY DEFAULT AS IDENTITY", 1, 0, 32, "d", false},
			{"smallint NULL GENERATED ALWAYS AS IDENTITY", 1, 0, 16, "a", true},
			{"bigint[] GENERATED ALWAYS AS IDENTITY", 1, 0, -1, "a", false},
			{"pg_catalog.text GENERATED ALWAYS AS IDENTITY", 1, 0, -1, "a", false},
			{"custom_type GENERATED ALWAYS AS IDENTITY", 1, 0, 0, "a", false},
			{"pg_catalog.int8(2) GENERATED ALWAYS AS IDENTITY", 1, 0, 0, "a", false},
			{"int GENERATED ALWAYS AS (1) STORED", 0, 1, 32, "a", false},
			{"bigint GENERATED ALWAYS AS IDENTITY GENERATED BY DEFAULT AS IDENTITY", 2, 0, 64, "a", false},
		} {
			sql := prefix + tc.decl
			if prefix[0] == 'C' {
				sql += ")"
			}
			t.Run(sql, func(t *testing.T) {
				s := extractPostgreSQLStatement(t, sql)
				var col spec.Column
				if len(s.DDL.Columns) > 0 {
					col = s.DDL.Columns[0]
				} else {
					col = *s.DDL.Alter[0].Column.Definition
				}
				g := col.PGGeneration
				if g == nil || g.IdentityCount != tc.identities || g.StoredCount != tc.stored || g.TypeWidth != tc.width || g.Mode != tc.mode || g.ExplicitNull != tc.null {
					t.Fatalf("facts=%+v, want %+v", g, tc)
				}
			})
		}
	}
}

func TestGenerationSequenceOptionsAreLossless(t *testing.T) {
	s := extractPostgreSQLStatement(t, "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY (START WITH 2147483648 MINVALUE -9223372036854775808 MAXVALUE 9223372036854775807 CACHE 2147483649 CYCLE NO CYCLE))")
	g := s.DDL.Columns[0].PGGeneration
	if g == nil || g.Unmodeled || len(g.Options) != 6 {
		t.Fatalf("facts=%+v", g)
	}
	for i, want := range []int64{2147483648, math.MinInt64, math.MaxInt64, 2147483649} {
		if g.Options[i].Value == nil || *g.Options[i].Value != want {
			t.Fatalf("option %d=%+v, want %d", i, g.Options[i], want)
		}
	}
	if g.Options[4].Kind != spec.SequenceOptionCycle || g.Options[5].Kind != spec.SequenceOptionNoCycle {
		t.Fatalf("duplicate cycle order lost: %+v", g.Options)
	}
	s = extractPostgreSQLStatement(t, "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY (NO MINVALUE NO MAXVALUE INCREMENT -1))")
	g = s.DDL.Columns[0].PGGeneration
	if g.Options[0].Kind != spec.SequenceOptionNoMinValue || g.Options[1].Kind != spec.SequenceOptionNoMaxValue || *g.Options[2].Value != -1 {
		t.Fatalf("valueless/descending facts lost: %+v", g)
	}
	s = extractPostgreSQLStatement(t, "CREATE TABLE t (id bigint GENERATED ALWAYS AS IDENTITY (START WITH 9223372036854775808))")
	if !s.DDL.Columns[0].PGGeneration.Unmodeled {
		t.Fatal("out-of-int64 option must not disappear")
	}
}
