func TestPGColumnTransitionSeam(t *testing.T) {
	for _, tc := range []struct {
		suffix, mode string
		count        int
		guard        bool
		kinds        []spec.SequenceOptionKind
	}{
		{"ADD GENERATED ALWAYS AS IDENTITY", "a", 1, false, nil},
		{"ADD GENERATED BY DEFAULT AS IDENTITY(CYCLE CACHE 0)", "d", 1, false, []spec.SequenceOptionKind{spec.SequenceOptionCycle, spec.SequenceOptionCache}},
		{"SET GENERATED ALWAYS SET GENERATED BY DEFAULT", "a", 2, false, nil},
		{"SET CYCLE SET NO CYCLE", "", 0, false, []spec.SequenceOptionKind{spec.SequenceOptionCycle, spec.SequenceOptionNoCycle}},
		{"RESTART", "", 0, false, []spec.SequenceOptionKind{spec.SequenceOptionRestart}},
		{"RESTART WITH 0", "", 0, false, []spec.SequenceOptionKind{spec.SequenceOptionRestartWith}},
		{"SET START WITH 5", "", 0, false, []spec.SequenceOptionKind{spec.SequenceOptionStartWith}},
		{"DROP IDENTITY", "", 0, false, nil},
		{"DROP IDENTITY IF EXISTS", "", 0, true, nil},
		{"DROP EXPRESSION IF EXISTS", "", 0, true, nil},
		{"SET DEFAULT 1", "", 0, false, nil},
		{"DROP DEFAULT", "", 0, false, nil},
		{"SET NOT NULL", "", 0, false, nil},
		{"DROP NOT NULL", "", 0, false, nil},
	} {
		t.Run(tc.suffix, func(t *testing.T) {
			s := extractPostgreSQLStatement(t, `ALTER TABLE app.t ALTER COLUMN "ID" `+tc.suffix)
			a := s.DDL.Alter[0]
			f := a.PGColumnTransition
			if a.Name != "ID" || f == nil || f.Unmodeled || f.Mode != tc.mode || f.ModeCount != tc.count || f.IfExists != tc.guard || len(f.Options) != len(tc.kinds) {
				t.Fatalf("action=%+v facts=%+v", a, f)
			}
			for i, k := range tc.kinds {
				if f.Options[i].Kind != k {
					t.Fatalf("options=%+v", f.Options)
				}
			}
		})
	}
}

func TestPGColumnTransitionInt64AndUnknown(t *testing.T) {
	s := extractPostgreSQLStatement(t, "ALTER TABLE t ALTER COLUMN id RESTART WITH 2147483648 SET INCREMENT -9223372036854775808 SET MAXVALUE 9223372036854775807")
	f := s.DDL.Alter[0].PGColumnTransition
	if f.Unmodeled || len(f.Options) != 3 {
		t.Fatalf("facts=%+v", f)
	}
	for i, v := range []int64{2147483648, math.MinInt64, math.MaxInt64} {
		if f.Options[i].Value == nil || *f.Options[i].Value != v {
			t.Fatalf("option=%+v want=%d", f.Options[i], v)
		}
	}
	for _, suffix := range []string{"RESTART WITH 9223372036854775808", "ADD GENERATED ALWAYS AS IDENTITY(SEQUENCE NAME special_sequence)"} {
		s = extractPostgreSQLStatement(t, "ALTER TABLE t ALTER COLUMN id "+suffix)
		f = s.DDL.Alter[0].PGColumnTransition
		if !f.Unmodeled {
			t.Fatalf("unknown option lost: %+v", f)
		}
	}
}

func TestPGColumnTransitionKeepsLegacyJSON(t *testing.T) {
	for _, pair := range [][2]string{
		{"SET CYCLE", "SET NO CYCLE"},
		{"SET CYCLE", "RESTART WITH 5"},
		{"DROP IDENTITY", "DROP IDENTITY IF EXISTS"},
		{"DROP EXPRESSION", "DROP EXPRESSION IF EXISTS"},
		{"ADD GENERATED BY DEFAULT AS IDENTITY(CYCLE)", "ADD GENERATED BY DEFAULT AS IDENTITY(CACHE 0)"},
		{"SET GENERATED ALWAYS", "SET GENERATED ALWAYS SET GENERATED BY DEFAULT"},
	} {
		a := extractPostgreSQLStatement(t, "ALTER TABLE t ALTER COLUMN id "+pair[0]).DDL.Alter[0]
		b := extractPostgreSQLStatement(t, "ALTER TABLE t ALTER COLUMN id "+pair[1]).DDL.Alter[0]
		x, _ := json.Marshal(a)
		y, _ := json.Marshal(b)
		if !bytes.Equal(x, y) || reflect.DeepEqual(a.PGColumnTransition, b.PGColumnTransition) {
			t.Fatalf("compatibility/losslessness failed: %s / %s", x, y)
		}
	}
	s := extractPostgreSQLStatement(t, "ALTER TABLE t ADD COLUMN id bigint GENERATED ALWAYS AS IDENTITY(CYCLE)")
	if s.DDL.Alter[0].PGColumnTransition != nil || s.DDL.Alter[0].Column.Definition.PGGeneration == nil {
		t.Fatal("D2 scope changed")
	}
}
